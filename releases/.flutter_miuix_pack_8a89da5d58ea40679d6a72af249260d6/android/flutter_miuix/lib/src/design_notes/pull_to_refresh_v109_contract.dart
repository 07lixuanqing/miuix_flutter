// MIUIX 1.0.9 PullToRefresh source-parity contract.
//
// This comment-only design contract keeps the upstream evidence beside the
// implementation. It is intentionally granular because every item below is
// a fidelity requirement, not optional explanatory prose.
//
// Public defaults and callback contract
// - PullToRefreshDefaults.color is Compose Color.Gray, exactly ARGB FF888888.
// - Material Colors.grey is FF9E9E9E and must not be substituted.
// - The default text style is 14sp, bold, and explicitly carries FF888888.
// - The source refresh callback has the synchronous Kotlin type `() -> Unit`.
// - The source owner hoists isRefreshing and changes it from that callback.
// - Flutter accepts a synchronous callback for the same state-hoisting form.
// - FutureOr retains the earlier non-hoisted convenience without changing it.
// - When isRefreshing is null, a returned Future owns refresh completion.
// - When isRefreshing is non-null, only its true-to-false change completes it.
// - The source reads every label with `getOrElse(index) { "" }`.
// - Empty and one-to-three-item localization lists therefore remain valid.
// - A missing phase paints an empty label without changing header geometry.
// - The source creates its orbit only during Refreshing.
// - Its initial orbit angle is remembered from a random integer in 0..360.
// - It then advances 360 degrees over 800ms with linear easing and restarts.
// - A later refresh on the same indicator reuses its remembered initial angle.
// - DropdownPage hoists isRefreshing and invokes a synchronous refresh setter.
// - Its launched completion waits 200ms, appends six rows, then clears loading.
// - The full refresh family lives in widgets/parts/pull_to_refresh.dart.
// - Progress indicators remain in widgets/parts/progress_scroll.dart.
// - Scrollbars and scroll physics live in widgets/parts/scroll.dart.
// - The split is mechanical and preserves private ownership of every painter.
//
// Idle 状态
// - 权威依据来自 MIUIX 1.0.9 PullToRefresh.kt，Flutter 实现不得自行改写其语义。
// - 核心不变量必须在每次状态更新后成立，并由公开状态对象同步暴露。
// - Flutter 映射应保持 Compose 的尺寸单位、状态顺序与绘制中心计算一致。
// - 视觉证据必须覆盖指示器、文字和内容三者的相对位置，不能只检查类名。
// - 交互证据必须由真实滚动通知或拖拽产生，不能直接伪造最终截图。
// - 边界情况必须覆盖零位移、极限位移、重复释放和异步完成。
// - 生命周期必须在组件卸载、控制器切换和动画取消时保持无异常。
// - 示例中的可见文字必须汉化，但组件默认行为仍要对应上游参数。
// - 回归测试必须对数值或像素建立明确断言，避免只验证没有抛错。
// - 完成门禁要求源码、测试、黄金图和真机行为共同支持这一条契约。
//
// Android 真实指针输入契约
// - Compose 与 Flutter 的滚动通知起点并不相同。
// - Android Compose 采用平台 ViewConfiguration 的触摸阈值。
// - Android 平台默认触摸阈值的基础值为 8dp。
// - Flutter 垂直拖动识别器的后备阈值为 18dp。
// - 只监听 Flutter OverscrollNotification 会丢失两者之间的首段位移。
// - 首段丢失会让原版已显示的圆环在 Flutter 中仍然不可见。
// - 首段丢失也会让同一手势在原版越过阈值而 Flutter 尚未越过。
// - 组件必须同时观察直接指针位移和标准滚动通知。
// - 直接指针位移用于校正触摸阈值差异。
// - 标准通知仍负责合成滚动、辅助功能滚动和测试通知兼容。
// - 校正目标是 Compose 扣除 8dp 后的累计位移。
// - 校正目标不是未经处理的完整指针位移。
// - 直接位移应按手势起点累计，不能逐事件盲目相加。
// - 逐事件盲目相加会在通知先到达时产生重复位移。
// - 当前原始触摸值必须从累计目标中扣除后再应用。
// - 通知先到或 Listener 先到都应得到相同最终结果。
// - 第二个 MOVE 必须使用从 DOWN 开始的累计距离。
// - 第二个 MOVE 不能再次加入第一个 MOVE 已经贡献的距离。
// - 多指输入不能替换已经拥有当前下拉手势的指针。
// - 非活动指针的 MOVE、UP 和 CANCEL 必须保持无效。
// - 水平意图不能启动下拉刷新。
// - 垂直距离必须大于水平距离才能进入直接拖动。
// - 关闭状态只允许向下位移打开刷新头。
// - 已打开状态允许向上位移逐步关闭刷新头。
// - 指针取消必须与指针抬起执行相同的释放清理。
// - ScrollEnd 与 PointerUp 可能同时触发释放。
// - 释放过程必须通过 processingRelease 防止重复启动。
// - 真实设备测试必须使用相同分辨率和相同移动坐标。
// - 当前基准设备为 1080x2400、420dpi。
// - 当前基准手势从物理坐标 540,700 开始。
// - 第一段 MOVE 到物理坐标 540,780。
// - 第二段 MOVE 到物理坐标 540,860。
// - 第一段移动后的卡片顶边基准为 428px。
// - 第二段移动后的卡片顶边基准为 520px。
// - 这些坐标同时由原版应用与 Flutter 应用实测取得。
// - 汉化文字可以改变字形宽度但不能改变头部结构高度。
// - 阈值胶囊的顶部、底部和中心必须继续使用原版公式。
// - 阈值文字必须位于胶囊下方 6dp 的源间距处。
// - 指针输入校正不得改写阻尼曲线。
// - 阻尼仍为 x - x² + x³ / 3。
// - 阻尼归一化范围仍为完整窗口高度。
// - 刷新阈值仍为窗口高度的二十四分之一。
//
// 顶部边界消费契约
// - Compose nested scroll 在子列表越过顶部前消费刷新位移。
// - Flutter 的 MiuixSpringScrollPhysics 允许列表像素进入负范围。
// - 若不拦截负范围，列表会在刷新头展开之外再次向下移动。
// - 这会形成一次头部位移和一次列表回弹的双重位移。
// - 仅关闭 overscroll indicator 不能修复实际负像素位置。
// - overscroll indicator 只控制附加绘制，不改变 ScrollPosition。
// - PullToRefresh 子树必须在顶部采用钳制边界条件。
// - 到达顶部前的合法列表滚动仍应由子列表消费。
// - 穿过顶部的剩余距离必须作为 OverscrollNotification 暴露。
// - 该剩余距离再由刷新状态机转换为原始触摸距离。
// - 刷新头可见时，列表本身必须锁定在当前边界。
// - 向上关闭刷新头时，列表不能同时向内容方向滚动。
// - Refreshing 状态下，列表不能响应用户滚动位移。
// - RefreshComplete 状态下也必须保持同样的锁定。
// - 底部边界不属于 PullToRefresh 的顶部消费范围。
// - 底部应继续委托给继承的 MIUIX 弹簧物理。
// - 因此不能用全局 ClampingScrollPhysics 替换整个列表物理。
// - 私有物理适配器只能改写顶部边界和刷新锁定状态。
// - 列表显式提供的 AlwaysScrollableScrollPhysics 必须继续有效。
// - 空内容列表仍然必须允许触发下拉刷新。
// - ScrollConfiguration 必须保留继承行为的其他参数。
// - 滚轮、触控板和鼠标拖动设备集合不能被意外重置。
// - 平台、滚动条策略和轴修饰键也必须继续继承。
// - 列表到顶部后的第一段剩余位移不能被重复使用。
// - 从非顶部开始的手势应持续等待子列表到达顶部。
// - 到达顶部的那一个事件用于建立新的直接位移基线。
// - 后续事件才从该基线开始累计直接拖动。
// - 若通知已应用同事件的剩余量，新的基线应保留该量。
// - 最新 ScrollMetrics 必须来自垂直滚动轴。
// - 水平子滚动的 metrics 不能覆盖垂直列表状态。
// - extentBefore 小于等于 0.5dp 视为位于顶部。
// - 该容差与现有通知处理保持一致。
//
// 回归验证契约
// - 单次 50dp 测试移动应先扣除 Android 8dp 触摸阈值。
// - 42dp 原始触摸距离应通过完整窗口阻尼计算。
// - 840dp 测试窗口的刷新阈值应为 35dp。
// - 单次移动后的阻尼距离应越过该 35dp 阈值。
// - 若错误扣除 Flutter 18dp，该测试会停留在阈值以下。
// - 第二次 50dp 移动后的累计原始距离应为 92dp。
// - 第二次结果必须直接由 92dp 计算，不能叠加首帧结果。
// - 测试必须断言公开 dragOffset 的数值误差小于 0.01dp。
// - 测试必须断言第二帧仍处于 ThresholdReached。
// - 测试必须断言列表顶边等于刷新头底边。
// - 该几何断言用于捕获列表负像素导致的双重位移。
// - 现有五状态测试必须继续覆盖 Pulling。
// - 现有五状态测试必须继续覆盖 ThresholdReached。
// - 现有五状态测试必须继续覆盖 Refreshing。
// - 现有五状态测试必须继续覆盖 RefreshComplete。
// - 现有五状态测试必须继续覆盖最终 Idle。
// - 阈值进入震动仍然只能在状态首次进入时触发一次。
// - 合成 null scrollDelta 通知仍然必须安全且无状态变化。
// - 组件卸载时未完成的刷新 Future 仍然不能产生异常。
// - 示例测试必须继续验证头部参与 Column 等价布局。
