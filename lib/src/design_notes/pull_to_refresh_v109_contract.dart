// MIUIX 1.0.9 PullToRefresh source-parity contract.
//
// This comment-only design contract keeps the upstream evidence beside the
// implementation. It is intentionally granular because every item below is
// a fidelity requirement, not optional explanatory prose.
//
// Public defaults and callback contract
// - PullToRefreshDefaults.color is Compose Color.Gray, exactly ARGB FF888888.
// - Material Colors.grey is FF9E9E9E and must not be substituted.
// - The default text style is 14sp, bold, and explicitly carries FF888888.
// - The source refresh callback has the synchronous Kotlin type `() -> Unit`.
// - The source owner hoists isRefreshing and changes it from that callback.
// - Flutter accepts a synchronous callback for the same state-hoisting form.
// - FutureOr retains the earlier non-hoisted convenience without changing it.
// - When isRefreshing is null, a returned Future owns refresh completion.
// - When isRefreshing is non-null, only its true-to-false change completes it.
// - The source reads every label with `getOrElse(index) { "" }`.
// - Empty and one-to-three-item localization lists therefore remain valid.
// - A missing phase paints an empty label without changing header geometry.
// - The source creates its orbit only during Refreshing.
// - Its initial orbit angle is remembered from a random integer in 0..360.
// - It then advances 360 degrees over 800ms with linear easing and restarts.
// - A later refresh on the same indicator reuses its remembered initial angle.
// - DropdownPage hoists isRefreshing and invokes a synchronous refresh setter.
// - Its launched completion waits 200ms, appends six rows, then clears loading.
// - The full refresh family lives in widgets/parts/pull_to_refresh.dart.
// - Progress indicators remain in widgets/parts/progress_scroll.dart.
// - Scrollbars and scroll physics live in widgets/parts/scroll.dart.
// - The split is mechanical and preserves private ownership of every painter.
//
// Idle 状态
// - 权威依据来自 MIUIX 1.0.9 PullToRefresh.kt，Flutter 实现不得自行改写其语义。
// - 核心不变量必须在每次状态更新后成立，并由公开状态对象同步暴露。
// - Flutter 映射应保持 Compose 的尺寸单位、状态顺序与绘制中心计算一致。
// - 视觉证据必须覆盖指示器、文字和内容三者的相对位置，不能只检查类名。
// - 交互证据必须由真实滚动通知或拖拽产生，不能直接伪造最终截图。
// - 边界情况必须覆盖零位移、极限位移、重复释放和异步完成。
// - 生命周期必须在组件卸载、控制器切换和动画取消时保持无异常。
// - 示例中的可见文字必须汉化，但组件默认行为仍要对应上游参数。
// - 回归测试必须对数值或像素建立明确断言，避免只验证没有抛错。
// - 完成门禁要求源码、测试、黄金图和真机行为共同支持这一条契约。
//
// 当前上游阈值模型核对记录
// - refreshThreshold 是完整阻尼拖动范围上的比例，不是屏幕高度上的直接比例。
// - refreshThreshold 的公开默认值是 0.25，输入必须被限制在零到一之间。
// - 非有限 refreshThreshold 必须退回默认值，不能把 NaN 传入布局和绘制。
// - 一次完整窗口高度的原始拖动经过三次阻尼多项式后得到窗口高度三分之一。
// - triggerProgressOffset 等于完整阻尼范围乘以 refreshThreshold。
// - refreshThresholdOffset 是固定视觉停靠点，等于窗口高度的二十四分之一。
// - triggerProgressOffset 决定何时进入 ThresholdReached，不能被视觉停靠点替代。
// - refreshThreshold 为零时，任何大于零的有效下拉都可以进入阈值状态。
// - refreshThreshold 为一时，必须达到完整阻尼范围才允许触发刷新。
// - pullProgress 使用视觉阈值和触发阈值中的较大者作为分母。
// - visualProgress 使用视觉阈值和触发阈值中的较小者完成指示器缩放。
// - fullDragProgress 始终以完整阻尼范围为分母，并限制在零到一之间。
// - 公开状态必须同时暴露视觉阈值、触发阈值、比例和完整范围进度。
// - 页面调整阈值后，下一次拖动必须立即使用新的触发距离。
//
// 当前上游状态机核对记录
// - Idle 表示没有可见头部，列表拥有普通滚动输入。
// - Pulling 表示存在正向拖动，但尚未达到配置的触发阈值。
// - ThresholdReached 表示释放后应开始刷新，同时保留胶囊形指示器。
// - Refreshing 表示刷新由外部布尔状态托管，组件只负责视觉状态。
// - RefreshComplete 表示完成动画正在收拢指示器与文字。
// - 释放前超过阈值时，回弹必须先落到固定视觉停靠点再开始旋转。
// - 释放前未到阈值时，回弹必须回到零并最终恢复 Idle。
// - 进入 ThresholdReached 时只发送一次阈值震动，连续移动不能重复发送。
// - 从阈值上方拉回阈值下方后，再次越过时允许发送新的阈值震动。
// - 刷新过程中新的拖动不能改变锁定的指示器状态。
// - 完成状态使用独立的二百毫秒动画，避免与位移弹簧相互取消。
// - 组件卸载时两个动画控制器都必须停止并释放。
// - 外部状态对象替换后，新对象必须立即收到当前内部状态快照。
// - 同一个指针会话只能由首个有效触点拥有，后续触点不能抢占。
//
// 外部刷新状态核对记录
// - isRefreshing 非空时，调用者是逻辑加载状态的唯一真值来源。
// - isRefreshing 从假变真且组件空闲时，指示器应以编程方式展开。
// - isRefreshing 从真变假且组件刷新时，组件应开始完成动画。
// - 工具栏刷新和手势刷新必须共用同一个页面级状态入口。
// - 页面刷新延迟为一百毫秒，与当前上游示例保持一致。
// - 页面完成一次刷新后必须追加六条下拉偏好行。
// - 快速真到假的状态脉冲不能让组件永久停留在 Refreshing。
// - 编程展开结束后必须在下一帧重新采样外部刷新状态。
// - 同步 onRefresh 回调可以在同一帧把外部状态提高为真。
// - 重新采样必须等待该父级重建生效，不能立即读取旧 widget 值。
// - isRefreshing 为空时保留 FutureOr 回调兼容形式，并等待异步完成。
// - 异步回调异常必须交给 FlutterError 报告，同时允许组件回收状态。
// - 重复点击刷新操作时，页面必须拒绝第二个并发加载批次。
// - 组件销毁后的延迟完成不能调用 setState 或访问无效上下文。
//
// 完整进度回调核对记录
// - onPullProgress 对应上游 fullDragProgress，而不是阈值相对 pullProgress。
// - 回调首次组合后必须收到当前值，包括初始零值。
// - 指针下拉、程序展开、回弹和完成动画都可以驱动进度变化。
// - 同一渲染帧中的多次内部更新必须合并为一次外部通知。
// - 回调不能在子组件构建阶段同步触发父组件 setState。
// - 回调排队时保存最新值，不能发送被后续移动覆盖的旧采样。
// - 未提供回调时不得额外安排无意义的帧回调。
// - 完整阻尼范围尚未计算时不得进行除法或发送非有限值。
// - 回调实例替换后，新实例必须收到当前进度快照。
// - 相同进度不应重复通知，避免页面进度卡无意义重建。
// - 页面展示值使用截断后的整数百分比，与 Kotlin toInt 行为一致。
// - 页面进度卡重建不能重置列表位置、选择项或刷新状态。
// - 回调结束后组件公开状态与页面显示百分比必须来自同一次采样。
// - 真机持续按下截图必须能观察到非零进度和对应阈值文字。
//
// 指示器几何核对记录
// - 视觉停靠点保持窗口高度二十四分之一，与用户阈值设置相互独立。
// - 刷新旋转圆环最终停留在视觉停靠点，而不是更深的触发点。
// - 阈值高于默认值时，胶囊长度反映超过视觉停靠点的额外位移。
// - 阈值低于视觉点时，指示器必须在更短拖动内完成缩放。
// - 下拉文字在 visualProgress 超过二分之一后才出现。
// - 下拉文字透明度从 visualProgress 的二分之一到一之间增长。
// - ThresholdReached 和 Refreshing 的状态文字保持完全不透明。
// - 完成文字随完成动画逐步消失，同时头部高度缩回列表顶部。
// - 头部参与纵向布局并把列表向下推，不能作为浮层覆盖第一行。
// - contentPadding 顶边只移动刷新指示器，列表仍由调用者拥有其内边距。
// - 极端下拉时使用有界 Stack 避免紧凑宿主产生 RenderFlex 溢出。
// - 圆环尺寸、线宽、圆角端点和八百毫秒转速保持上游常量。
// - 刷新旋转起始相位可以随机，但停止后必须回到记忆的初始相位。
// - 绘制参数必须在进入 Canvas 前完成有限值和范围约束。
//
// 页面初始布局核对记录
// - 顶部应用栏标题保留上游 Popup 语义并显示为汉化的弹出菜单。
// - 返回按钮和刷新按钮占用与原版相同的四十 dp 动作槽。
// - 列表顶部内容从应用栏安全内边距再加十二 dp 开始。
// - 进度卡自身拥有水平十二 dp 和垂直八 dp 外边距。
// - 列表本身不能再添加水平十二 dp，否则会形成双重缩进。
// - 进度卡角半径为十二 dp，内部四边距为十六 dp。
// - 进度卡使用 surfaceContainer，按下反馈使用 Sink 并显示指示层。
// - 进度卡第一行显示完整拖动进度，第二行显示配置阈值。
// - 汉化 body1 行盒在 420dpi 设备上保持四十九个物理像素。
// - 汉化 body2 行盒在 420dpi 设备上保持四十三个物理像素。
// - 两个固定行盒防止 CJK 字体回退让卡片累计增高八个物理像素。
// - 同机基准中的进度卡中心区域为 y=363 到 y=539。
// - 进度卡之后保留八 dp 下边距，分组第一行从 y=560 开始。
