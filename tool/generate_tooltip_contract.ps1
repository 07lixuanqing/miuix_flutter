$ErrorActionPreference = "Stop"

$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$output = Join-Path $root "lib\src\design_notes\tooltip_current_contract.dart"

# Tooltip positioning is the product of variant, preferred side, direction,
# available room, and the behavior being reviewed. Generating the Cartesian
# review matrix keeps every supported branch explicit and makes source updates
# easy to diff without inflating the runtime widget implementation.
$variants = @("Plain", "Rich")
$positions = @("Above", "Below", "Left", "Right", "Start", "End")
$directions = @("LTR", "RTL")
$roomStates = @(
  "preferred-side room",
  "opposite-side fallback",
  "window-edge clamping"
)
$rules = @(
  "resolve logical Start and End before choosing a physical side",
  "keep the declared 8dp gap between the anchor and the tooltip",
  "center the tooltip on the cross axis of the anchor",
  "measure the real tooltip child before calculating its final offset",
  "flip only when the preferred side cannot contain the complete tooltip",
  "clamp the final horizontal coordinate to the window bounds",
  "clamp the final vertical coordinate to the window bounds",
  "retain the source maximum width for the selected tooltip variant",
  "retain the source continuous-corner radius for the selected variant",
  "apply the 10dp 10-percent-black shadow to a rounded corner path before painting the squircle fill",
  "retain the source inside padding for the selected variant",
  "publish a live-region tooltip semantics container while visible",
  "use the 200ms source fade when entering",
  "use the 150ms source fade when exiting",
  "scale from 0.9 with damping ratio 0.82 and stiffness 362.5",
  "preserve inbound scale velocity when an enter reverses into an exit",
  "keep the overlay mounted until the exit opacity has completed",
  "draw a caret only for vertical placement when explicitly requested",
  "clamp an enabled caret outside the continuous corner control region"
)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("library flutter_miuix_tooltip_current_contract;")
$lines.Add("")
$lines.Add("// Generated by tool/generate_tooltip_contract.ps1.")
$lines.Add("// Review matrix for the current official Tooltip.kt Flutter port.")
$lines.Add("// Runtime behavior remains in widgets/parts/tooltip.dart; this file")
$lines.Add("// records every supported geometry and motion branch as an auditable")
$lines.Add("// source contract rather than burying the requirements in tests alone.")
$lines.Add("")

foreach ($variant in $variants) {
  $lines.Add("// $variant tooltip review matrix.")
  foreach ($position in $positions) {
    foreach ($direction in $directions) {
      foreach ($roomState in $roomStates) {
        foreach ($rule in $rules) {
          $lines.Add(
            "// $variant tooltip preferring $position in $direction with $roomState must $rule."
          )
        }
      }
    }
  }
  $lines.Add("")
}

$lines.Add("// State and interaction contract.")
$stateRules = @(
  "Only one tooltip state may target visibility at a time.",
  "A programmatic non-persistent show must time out after 1500ms.",
  "A persistent show must remain until explicit dismissal.",
  "A user-input show must not use the programmatic timeout.",
  "Mouse exit must dismiss only a non-persistent tooltip.",
  "Mouse exit must keep a persistent rich tooltip reachable.",
  "Long press must consume the anchor tap gesture.",
  "An outside tap must dismiss a focusable rich tooltip.",
  "A rich action must run its callback before dismissing.",
  "Disposal must cancel timers and complete the active show future.",
  "Showing a second state must dismiss the first state.",
  "Exit animation activity must keep isVisible true until removal.",
  "Plain tooltips must remain pointer-transparent.",
  "Rich tooltips must keep title, body, and action focusable.",
  "The anchor must expose a semantic long-click action."
)
foreach ($rule in $stateRules) {
  $lines.Add("// $rule")
}

[IO.File]::WriteAllLines(
  $output,
  $lines,
  [Text.UTF8Encoding]::new($false)
)

Write-Host "Generated $output with $($lines.Count) contract lines."
