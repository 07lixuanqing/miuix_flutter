# `MiuixColorSchemeMode` predates the current source controller and describes
# the package's former preset/custom/platform source metadata. The actual
# six-branch upstream `ColorSchemeMode` is `MiuixColorMode`; keep the legacy
# name visible to existing callers without using it as false parity evidence.
$compatibilityExtensions = @("MiuixColorSchemeMode")

$missing = @()
$covered = @()
foreach ($entry in $mappings.GetEnumerator()) {
  if ($source -match "\b$($entry.Value)\b") {
    $covered += "$($entry.Key) -> $($entry.Value)"
  } else {
    $missing += "$($entry.Key) -> $($entry.Value)"
  }
}

