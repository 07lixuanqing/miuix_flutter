Write-Host "Covered mappings: $($covered.Count)"
Write-Host "Missing mappings: $($missing.Count)"
Write-Host "Compatibility extensions excluded from upstream count: $($compatibilityExtensions.Count)"

if ($missing.Count -gt 0) {
  $missing | ForEach-Object { Write-Host "MISSING $_" }
  throw "Missing MIUIX component mappings"
}

