$allSource = ($sourceFiles | ForEach-Object {
  # Dart source is UTF-8. Being explicit keeps Windows PowerShell 5.1 and
  # PowerShell 7 from decoding localized documentation differently.
  Get-Content -Encoding UTF8 $_.FullName
}) -join "`n"
$missing = @()
foreach ($name in $requiredNames) {
  if ($allSource -notmatch "\b$name\b") {
    $missing += $name
  }
}

if ($missing.Count -gt 0) {
  throw "Missing required component names: $($missing -join ', ')"
}

$nonEmptyLines = 0
$commentLines = 0
# Generated icon tables are mechanically emitted from the upstream font map.
# Counting their constant declarations as hand-maintained implementation code
# would make the ratio depend on icon count and encourage meaningless comments
# in files that are overwritten by the generator. Structural name checks above
# still inspect every Dart file; only the documentation ratio excludes *.g.dart.
$commentScopeFiles = @($sourceFiles | Where-Object {
  $_.Name -notlike "*.g.dart"
})
foreach ($file in $commentScopeFiles) {
  foreach ($line in Get-Content -Encoding UTF8 $file.FullName) {
    $trimmed = $line.Trim()
    if ($trimmed.Length -eq 0) {
      continue
    }
    $nonEmptyLines++
    if ($trimmed.StartsWith("//") -or $trimmed.StartsWith("/*") -or $trimmed.StartsWith("*")) {
      $commentLines++
    }
  }
}

if ($nonEmptyLines -eq 0) {
  throw "No Dart source lines found"
}

$ratio = [math]::Round(($commentLines / $nonEmptyLines) * 100, 2)
if ($ratio -lt 50) {
  throw "Comment ratio $ratio% ($commentLines / $nonEmptyLines non-empty lines) is below the 50% target"
}

Write-Host "Verified package structure."
Write-Host "Verified $($requiredNames.Count) required component names."
Write-Host "Comment ratio: $ratio% ($commentLines / $nonEmptyLines hand-maintained non-empty lines)."
